import fs from 'node:fs';
import path from 'node:path';
import {spawn} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {JsonRpcProvider,ContractFactory,HDNodeWallet,NonceManager} from 'ethers';
const here=path.dirname(fileURLToPath(import.meta.url));
const anvil=process.env.ANVIL_BIN||path.join(here,'node_modules/.bin/anvil');
const mockFile=process.env.MOCK_USDC_ARTIFACT;
if(!mockFile)throw Error('Set MOCK_USDC_ARTIFACT to the locally compiled MockUSDC artifact');
const parent=path.join(here,'rehearsal-bootstrap-'+Date.now());fs.mkdirSync(parent);
const server=spawn(anvil,['--chain-id','84532','--port','18547','--gas-price','1000000','--base-fee','0','--disable-min-priority-fee','--silent'],{stdio:'ignore'});
process.on('exit',()=>server.kill('SIGTERM'));
const p=new JsonRpcProvider('http://127.0.0.1:18547',undefined,{cacheTimeout:0});p.pollingInterval=50;
await new Promise(r=>setTimeout(r,1000));
const wallet=HDNodeWallet.fromPhrase('test test test test test test test test test test test junk').connect(p);
const signer=new NonceManager(wallet);
const mock=JSON.parse(fs.readFileSync(mockFile));
const token=await new ContractFactory(mock.abi,mock.bytecode.object,signer).deploy();await token.waitForDeployment();
await(await token.mint(wallet.address,1000000000n)).wait();
const artifact=JSON.parse(fs.readFileSync(path.join(here,'artifact.json')));
const gt=await new ContractFactory(artifact.abi,artifact.bytecode,signer).deploy(token.target,wallet.address,wallet.address,wallet.address,6000000n,1000000n);
await gt.waitForDeployment();
const common={...process.env,REHEARSAL:'1',RPC_URL:'http://127.0.0.1:18547',TEST_TOKEN_ADDRESS:token.target,TEST_WALLET_PRIVATE_KEY:wallet.privateKey,COLDSTART_GT:gt.target,COLDSTART_DEPLOYMENT_HASH:gt.deploymentTransaction().hash};
function run(file,extra,args=[]){return new Promise((resolve,reject)=>{const child=spawn(process.execPath,[file,...args],{cwd:here,env:{...common,...extra},stdio:'inherit'});child.on('error',reject);child.on('exit',code=>resolve(code??1));});}
const stopped=path.join(parent,'stopped'),resumed=path.join(parent,'resumed');
const first=await run('coldstart.mjs',{COLDSTART_OUT:stopped,REHEARSAL_STOP_AFTER_LABEL:'gas-backer-08'});
if(first!==1||!fs.existsSync(path.join(stopped,'stopped.json')))throw Error('Expected deliberate bootstrap checkpoint stop');
const second=await run('coldstart.mjs',{COLDSTART_OUT:resumed,COLDSTART_BOOTSTRAP_RESUME:stopped,REHEARSAL_STOP_AFTER_LABEL:''});
if(second!==0)throw Error('Bootstrap resume rehearsal failed');
const third=await run('verify.mjs',{},['--offline','--evidence',resumed]);
if(third!==0)throw Error('Resumed packet algebra verification failed');
console.log('BOOTSTRAP_REHEARSAL_COMPLETE '+JSON.stringify({packet:resumed,summary:JSON.parse(fs.readFileSync(path.join(resumed,'summary.json'))).counts}));
server.kill('SIGTERM');
